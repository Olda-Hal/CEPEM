import { PatientDetail } from '../types';

export interface IntakeSummary {
  weight: string | null;
  height: string | null;
  medications: string[];
  healthStatus: string[];
  covid: string[];
  gynecology: string[];
  notes: string | null;
  rawLines: string[];
}

const emptySummary = (): IntakeSummary => ({
  weight: null,
  height: null,
  medications: [],
  healthStatus: [],
  covid: [],
  gynecology: [],
  notes: null,
  rawLines: []
});

/** Line prefixes that belong to the gynecology section of an intake comment. */
const GYNECOLOGY_PREFIXES = [
  'Poslední menzes:',
  'Cyklus opakování:',
  'Roky od poslední menzes:',
  'Rodila:',
  'Kojila:',
  'Záněty při kojení:',
  'Končilo kojení zánětem:',
  'Antikoncepce:',
  'Estrogen:',
  'Interrupce:',
  'Potrat:',
  'Úraz prsu:',
  'RTG mamograf:',
  'Biopsie prsu:',
  'Implantáty:',
  'Operace prsu:',
  'Nádory v rodině:'
];

/**
 * Parses the free-text intake comment (historically generated by the
 * backend from submitted intake forms) into structured sections.
 * The Czech label prefixes are part of the stored data contract.
 */
export const parseIntakeSummary = (comment?: string | null): IntakeSummary => {
  const summary = emptySummary();

  if (!comment) {
    return summary;
  }

  const lines = comment
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
  summary.rawLines = lines;

  lines.forEach((line) => {
    if (line.startsWith('Váha:')) {
      summary.weight = line.replace('Váha:', '').trim();
      return;
    }

    if (line.startsWith('Výška:')) {
      summary.height = line.replace('Výška:', '').trim();
      return;
    }

    if (line.startsWith('Léky:')) {
      summary.medications.push(line.replace('Léky:', '').trim());
      return;
    }

    if (line.startsWith('Zdravotní stav:')) {
      summary.healthStatus.push(line.replace('Zdravotní stav:', '').trim());
      return;
    }

    if (line.startsWith('COVID:') || line.startsWith('Vakcinace')) {
      summary.covid.push(line);
      return;
    }

    if (GYNECOLOGY_PREFIXES.some((prefix) => line.startsWith(prefix))) {
      summary.gynecology.push(line);
      return;
    }

    if (line.startsWith('Poznámky:')) {
      summary.notes = line.replace('Poznámky:', '').trim();
      return;
    }
  });

  return summary;
};

/**
 * Builds the same structured summary directly from a submitted intake
 * form (the newer storage format), mirroring what the backend used to
 * flatten into the comment text.
 */
export const formSubmissionToIntakeSummary = (
  formSubmission?: PatientDetail['formSubmission'] | null
): IntakeSummary => {
  const summary = emptySummary();

  if (!formSubmission) {
    return summary;
  }

  const medicationList: string[] = [];

  if (formSubmission.medication?.medBloodPressure) medicationList.push('Léky na krevní tlak');
  if (formSubmission.medication?.medHeart) medicationList.push('Léky na srdce');
  if (formSubmission.medication?.medCholesterol) medicationList.push('Léky na cholesterol');
  if (formSubmission.medication?.medBloodThinners) medicationList.push('Antikoagulancia');
  if (formSubmission.medication?.medDiabetes) medicationList.push('Léky na cukrovku');
  if (formSubmission.medication?.medThyroid) medicationList.push('Léky na štítnou žlázu');
  if (formSubmission.medication?.medNerves) medicationList.push('Léky na nervy');
  if (formSubmission.medication?.medPsych) medicationList.push('Psychofarmaká');
  if (formSubmission.medication?.medDigestion) medicationList.push('Léky na trávení');
  if (formSubmission.medication?.medPain) medicationList.push('Bolest léky');
  if (formSubmission.medication?.medDehydration) medicationList.push('Hydratace léky');
  if (formSubmission.medication?.medBreathing) medicationList.push('Léky na dýchání');
  if (formSubmission.medication?.medAntibiotics) medicationList.push('Antibiotika');
  if (formSubmission.medication?.medSupplements) medicationList.push('Doplňky stravy');
  if (formSubmission.medication?.medAllergies) medicationList.push('Léky na alergie');

  summary.medications = medicationList;

  const healthStatusList: string[] = [];

  if (formSubmission.lifestyle?.poorSleep) healthStatusList.push('Špatný spánek');
  if (formSubmission.lifestyle?.digestiveIssues) healthStatusList.push('Zažívací problémy');
  if (formSubmission.lifestyle?.physicalStress) healthStatusList.push('Fyzický stres');
  if (formSubmission.lifestyle?.mentalStress) healthStatusList.push('Duševní stres');
  if (formSubmission.lifestyle?.smoking) healthStatusList.push('Kouření');
  if (formSubmission.lifestyle?.fatigue) healthStatusList.push('Únava');

  summary.healthStatus = healthStatusList;
  summary.notes = formSubmission.lifestyle?.additionalHealthInfo || null;

  const covidList: string[] = [];
  formSubmission.sicknessHistories?.forEach((history) => {
    if (history.hadSickness) {
      covidList.push(`${history.sicknessName}: ano`);
    }
    if (history.vaccinated) {
      covidList.push(`Vakcinace (${history.sicknessName}): ${history.vaccinationWhen || 'ano'}`);
    }
  });
  summary.covid = covidList;

  const reproductive = formSubmission.reproductiveHealth;
  const gynecologyList: string[] = [];

  if (reproductive?.lastMenstruationDate)
    gynecologyList.push(`Poslední menzes: ${reproductive.lastMenstruationDate}`);
  if (reproductive?.menstruationCycleDays)
    gynecologyList.push(`Cyklus opakování: ${reproductive.menstruationCycleDays} dní`);
  if (reproductive?.yearsSinceLastMenstruation)
    gynecologyList.push(`Roky od poslední menzes: ${reproductive.yearsSinceLastMenstruation}`);
  if (reproductive?.gaveBirth)
    gynecologyList.push(
      `Rodila: ano${reproductive.birthCount ? ` (${reproductive.birthCount}x)` : ''}`
    );
  if (reproductive?.breastfed)
    gynecologyList.push(
      `Kojila: ano${reproductive.breastfeedingMonths ? ` (${reproductive.breastfeedingMonths} měsíců)` : ''}`
    );
  if (reproductive?.breastfeedingInflammation) gynecologyList.push('Záněty při kojení: ano');
  if (reproductive?.endedWithInflammation) gynecologyList.push('Končilo kojení zánětem: ano');
  if (reproductive?.contraception)
    gynecologyList.push(
      `Antikoncepce: ano${reproductive.contraceptionDuration ? ` (${reproductive.contraceptionDuration})` : ''}`
    );
  if (reproductive?.estrogen)
    gynecologyList.push(
      `Estrogen: ano${reproductive.estrogenType ? ` (${reproductive.estrogenType})` : ''}`
    );
  if (reproductive?.interruption)
    gynecologyList.push(
      `Interrupce: ano${reproductive.interruptionCount ? ` (${reproductive.interruptionCount}x)` : ''}`
    );
  if (reproductive?.miscarriage)
    gynecologyList.push(
      `Potrat: ano${reproductive.miscarriageCount ? ` (${reproductive.miscarriageCount}x)` : ''}`
    );
  if (reproductive?.breastInjury) gynecologyList.push('Úraz prsu: ano');
  if (reproductive?.mammogram)
    gynecologyList.push(
      `RTG mamograf: ano${reproductive.mammogramCount ? ` (${reproductive.mammogramCount}x)` : ''}`
    );
  if (reproductive?.breastBiopsy) gynecologyList.push('Biopsie prsu: ano');
  if (reproductive?.breastImplants) gynecologyList.push('Implantáty: ano');
  if (reproductive?.breastSurgery)
    gynecologyList.push(
      `Operace prsu: ano${reproductive.breastSurgeryType ? ` (${reproductive.breastSurgeryType})` : ''}`
    );
  if (reproductive?.familyTumors)
    gynecologyList.push(
      `Nádory v rodině: ano${reproductive.familyTumorType ? ` (${reproductive.familyTumorType})` : ''}`
    );

  summary.gynecology = gynecologyList;

  return summary;
};
